create policy "tracker users can manage own logs" on public.study_logs for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "tracker users can manage own timers" on public.timer_sessions for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "tracker users can manage own tasks" on public.tasks for all using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy "tracker users can manage own goals" on public.goals for all using (user_id = auth.uid()) with check (user_id = auth.uid());
